-- Review-reply delegation tasks — docs/vendor_server_contract_v1.md §4: the PC drafts, the seller approves an exact
-- version, a delegate claims it and posts it by hand in Seller Center, and reports what happened. This server holds
-- the state of record. Written to run unchanged on PostgreSQL and on H2 in PostgreSQL mode.

create table reply_tasks (
    id                       uuid primary key,
    store_id                 uuid not null references stores (id),
    review_id                uuid not null references store_reviews (id),
    state                    varchar(20) not null,
    -- Optimistic lock: every transition is UPDATE … WHERE state = ? AND state_version = ?.
    state_version            integer not null,
    draft_version            integer not null,
    draft_body               text not null,
    draft_fingerprint        char(64) not null,
    -- Draft provenance (§4.1): the server carries these and judges none of them.
    review_body_fingerprint  char(64) not null,
    generated_at             timestamp with time zone not null,
    knowledge_fp             varchar(64) not null,
    policy_fp                varchar(64) not null,
    voice_fp                 varchar(64) not null,
    edited_on_mobile         boolean not null,
    server_checks            varchar(200) not null,
    pc_recheck_version       integer,
    pc_recheck               varchar(200),
    approved_version         integer,
    approved_fingerprint     char(64),
    approved_by              uuid references seller_accounts (id),
    approved_at              timestamp with time zone,
    claimed_by               uuid references delegates (id),
    claimed_at               timestamp with time zone,
    outcome                  varchar(16),
    posted_fingerprint       char(64),
    checked_at               timestamp with time zone,
    reported_at              timestamp with time zone,
    report_method            varchar(32),
    created_at               timestamp with time zone not null,
    updated_at               timestamp with time zone not null,
    -- The review this task is still open on; cleared when the task ends. Unique, so a review never has two open
    -- tasks however two PCs race (several NULLs are allowed on PostgreSQL and H2 alike).
    open_review_id           uuid unique
);

create index reply_tasks_store_state_idx on reply_tasks (store_id, state);
create index reply_tasks_review_idx on reply_tasks (review_id);

-- What a PC syncs: every transition of a store's tasks, in order (the server is the state of record).
create table reply_task_changes (
    seq      bigint generated by default as identity primary key,
    store_id uuid not null references stores (id),
    task_id  uuid not null references reply_tasks (id),
    state    varchar(20) not null,
    at       timestamp with time zone not null
);

create index reply_task_changes_store_seq_idx on reply_task_changes (store_id, seq);

-- A write sent twice with the same commandId happens once (§4.1).
create table task_commands (
    command_id varchar(100) primary key,
    task_id    uuid not null references reply_tasks (id),
    action     varchar(24) not null,
    at         timestamp with time zone not null
);
