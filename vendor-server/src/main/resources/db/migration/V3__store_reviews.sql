-- Review exchange — docs/vendor_server_contract_v1.md §3: a delegate uploads a store's review export, the seller's
-- PC pulls what is new or changed. Written to run unchanged on PostgreSQL and on H2 in PostgreSQL mode.
--
-- Only the columns contract §3.1 allows are kept. Reviewer, order number, member-entered fields and the operating
-- extras of the export never reach a row; the file itself is never written to disk.

-- One audit row per upload: who, when, what it did. No file content.
create table review_uploads (
    id                  uuid primary key,
    store_id            uuid not null references stores (id),
    delegate_id         uuid not null references delegates (id),
    uploaded_at         timestamp with time zone not null,
    row_count           integer not null,
    new_count           integer not null,
    changed_count       integer not null,
    replied_count       integer not null,
    unchanged_count     integer not null,
    attachments_dropped integer not null
);

create index review_uploads_store_idx on review_uploads (store_id);

create table store_reviews (
    id                 uuid primary key,
    store_id           uuid not null references stores (id),
    review_no          varchar(20) not null,
    product_no         varchar(40),
    product_name       varchar(300),
    review_kind        varchar(40),
    rating             smallint not null,
    body               text not null,
    body_fingerprint   char(64) not null,
    -- The export's one attachment address (first attachment only), kept only on the marketplace image host.
    attachment_url     varchar(1000),
    attachment_kind    varchar(16),
    written_at         timestamp with time zone not null,
    modified_at        timestamp with time zone,
    display_state      varchar(40),
    replied            boolean not null,
    replied_at         timestamp with time zone,
    related_review_no  varchar(20),
    related_body       text,
    first_upload_id    uuid not null references review_uploads (id),
    last_upload_id     uuid not null references review_uploads (id),
    created_at         timestamp with time zone not null,
    updated_at         timestamp with time zone not null,
    -- Retention (contract §6, D4): the 90 days of a no-reply review start once the PC has saved it AND it was
    -- judged to need no reply; purge_after is set when both are known, and never moved later by a re-upload.
    pc_saved_at        timestamp with time zone,
    no_reply_needed_at timestamp with time zone,
    purge_after        timestamp with time zone,
    constraint store_reviews_store_review_no unique (store_id, review_no)
);

-- What a PC pulls: an append-only, per-store ordered list of what happened to which review.
create table store_review_events (
    seq       bigint generated by default as identity primary key,
    store_id  uuid not null references stores (id),
    review_id uuid not null references store_reviews (id),
    kind      varchar(16) not null,
    at        timestamp with time zone not null
);

create index store_review_events_store_seq_idx on store_review_events (store_id, seq);

-- How far each PC of the account has confirmed saving, per store.
create table store_review_acks (
    store_id   uuid not null references stores (id),
    install_id uuid not null references installs (id),
    acked_seq  bigint not null,
    acked_at   timestamp with time zone not null,
    primary key (store_id, install_id)
);
